// First launch: sign-in screen after the intro, "Continue without an account", and the "Make this a shared profile" option.
import {createRequire} from 'node:module';
import {build} from 'esbuild';
import {mkdirSync,cpSync,readFileSync,existsSync} from 'node:fs';
import http from 'node:http';import path from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const CHROME=process.env.CHROME_PATH||'/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell';
const OUT='tests/.tmp';mkdirSync(OUT+'/www',{recursive:true});
await build({entryPoints:['tests/browser/harness.js'],bundle:true,format:'iife',outfile:OUT+'/www/app.js',logLevel:'error'});
for(const f of ['app.css','index.html','fonts'])cpSync('www/'+f,OUT+'/www/'+f,{recursive:true});
const srv=http.createServer((q,r)=>{const u=q.url.split('?')[0];const f=path.join(OUT,'www',u==='/'?'index.html':u);if(!existsSync(f)){r.writeHead(404);r.end();return;}r.writeHead(200,{'content-type':f.endsWith('.js')?'text/javascript':f.endsWith('.css')?'text/css':f.endsWith('.woff2')?'font/woff2':'text/html'});r.end(readFileSync(f));}).listen(0);
const browser=await chromium.launch({executablePath:CHROME,args:['--no-sandbox']});
const ctx=await browser.newContext({viewport:{width:390,height:844},locale:'en-IN'});
const page=await ctx.newPage();page.setDefaultTimeout(6000);
const errs=[];page.on('pageerror',e=>errs.push(String(e)));
let fails=0;const ok=(n,c)=>{console.log((c?'PASS ':'FAIL ')+n);if(!c)fails++;};
await page.goto(`http://localhost:${srv.address().port}/`);await page.waitForSelector('html.ready');
ok('first launch shows the intro first',await page.evaluate(()=>!!document.querySelector('[data-act="start"]')));
await page.click('[data-act="start"]');
ok('after the intro the sign-in screen is shown',(await page.innerText('h1')).includes('Sign in'));
ok('it has no back button',await page.evaluate(()=>!document.querySelector('.hd [data-act="back"]')));
ok('it offers to continue without an account',(await page.innerText('#screen')).includes('Continue without an account'));
ok('it offers Forgot password',(await page.innerText('#screen')).includes('Forgot password?'));
await page.click('[data-act="acTab"][data-v="up"]');
ok('Create account asks for a name',await page.evaluate(()=>!!document.getElementById('acName')));
await page.click('[data-act="acSkip"]');
ok('continuing without an account opens Home',await page.evaluate(()=>!!document.querySelector('[data-act="tab"][data-t="home"]')&&!document.getElementById('acEmail')));
ok('the intro is not shown again',await page.evaluate(()=>window.__t.S.onboarded===true));
await page.click('[data-act="tab"][data-t="settings"]');
ok('Settings offers "Make this a shared profile" on a personal profile',await page.evaluate(()=>!!document.querySelector('[data-act="profShareThis"]')));
await page.click('[data-act="profShareThis"]');
ok('it opens New profile with Shared and the import already on',await page.evaluate(()=>document.getElementById('pfShared').checked&&!!document.getElementById('pfName')));
ok('no page errors',errs.length===0);if(errs.length)console.log(errs);
await browser.close();srv.close();process.exit(fails?1:0);
