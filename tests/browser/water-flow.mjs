// The Water Bottles walk-through from the brief (steps 1-12), driven through the real screens.
import {createRequire} from 'node:module';
import {build} from 'esbuild';
import {mkdirSync,cpSync,readFileSync,existsSync} from 'node:fs';
import http from 'node:http';import path from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const CHROME=process.env.CHROME_PATH||'/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell';
const OUT='tests/.tmp';mkdirSync(OUT+'/www',{recursive:true});
await build({entryPoints:['tests/browser/harness.js'],bundle:true,format:'iife',outfile:OUT+'/www/app.js',logLevel:'error'});
for(const f of ['app.css','index.html','fonts'])cpSync('www/'+f,OUT+'/www/'+f,{recursive:true});
const srv=http.createServer((q,r)=>{const u=q.url.split('?')[0];const f=path.join(OUT,'www',u==='/'?'index.html':u);if(!existsSync(f)){r.writeHead(404);r.end();return;}r.writeHead(200,{'content-type':f.endsWith('.js')?'text/javascript':f.endsWith('.css')?'text/css':'text/html'});r.end(readFileSync(f));}).listen(0);
const browser=await chromium.launch({executablePath:CHROME,args:['--no-sandbox']});
const page=await (await browser.newContext({reducedMotion:'reduce',viewport:{width:390,height:844},locale:'en-IN'})).newPage();page.setDefaultTimeout(4000);
let fails=0;const ok=(n,c)=>{console.log((c?'PASS ':'FAIL ')+n);if(!c)fails++;};
await page.goto(`http://localhost:${srv.address().port}/`);await page.waitForSelector('html.ready');
const txt=()=>page.evaluate(()=>document.querySelector('#screen').innerText);
const day=n=>page.evaluate(n=>{const d=new Date();return d.getFullYear()+'-'+String(d.getMonth()+1).padStart(2,'0')+'-'+String(n).padStart(2,'0');},n);
await page.click('[data-act=start]');
await page.click('[data-act=pick]');await page.click('[data-act=pickGo][data-id=water]');
ok('1-2 first visit asks for the price per bottle',(await txt()).includes('price per bottle')||(await txt()).includes('Price per bottle'));
await page.click('[data-act=wSetupSave]');ok('validation: empty price is refused',(await page.textContent('#wsErr')).length>0);
await page.fill('#wsp','60');await page.click('[data-act=wSetupSave]');
ok('3-4 saved; calendar opens directly with ₹60 shown',(await txt()).includes('₹60 / bottle'));
await page.click(`[data-act=wDay][data-date="${await day(1)}"]`);await page.click('[data-act=wAdd]');
await page.fill('#f_qty','3');
const total=await page.evaluate(()=>{const e=document.querySelector('#f_total');return e?(e.value||e.textContent):document.querySelector('#layer,#screen').innerText;});
ok('5-7 quantity 3 shows total ₹180 automatically',/180/.test(total)||(await txt()).includes('₹180'));
await page.click('[data-act=saveForm]');
await page.click('[data-act=wTab][data-v=hist]').catch(()=>page.click('[data-act=wTab] >> nth=1'));
let t=await txt();
ok('8-9 entry appears in the monthly history (₹180, 3 bottles)',t.includes('₹180')&&/3/.test(t));
await page.click('[data-act=wPrice]');await page.fill('[data-d=np]','65');await page.click('[data-act=savePrice]');
await page.click('[data-act=wTab] >> nth=0');await page.click(`[data-act=wDay][data-date="${await page.evaluate(()=>new Date().toISOString().slice(0,10).replace(/^(\d{4})-(\d\d)-(\d\d)$/,(m,y,mo,d)=>{const n=new Date();return n.getFullYear()+'-'+String(n.getMonth()+1).padStart(2,'0')+'-'+String(n.getDate()).padStart(2,'0');}))}"]`);await page.click('[data-act=wAdd]');await page.fill('#f_qty','1');await page.click('[data-act=saveForm]');
await page.click('[data-act=wTab] >> nth=1');t=await txt();
ok('10-12 old record keeps ₹60 per bottle, new record uses ₹65',t.includes('₹180')&&t.includes('₹65'));
const S=await page.evaluate(()=>window.__t.S.records.filter(r=>r.cat==='water').map(r=>[r.unitP,r.amountP]).sort());
ok('stored amounts: 3 x ₹60 = ₹180 and 1 x ₹65 = ₹65 (integer paise)',JSON.stringify(S)===JSON.stringify([[6500,6500],[6000,18000]].sort()));
ok('monthly total = ₹245 and 4 bottles',t.includes('₹245')&&/Bottles received\s*4/.test(t));
await page.click('[data-act=wPrice]').catch(()=>{});
await browser.close();srv.close();process.exit(fails?1:0);
