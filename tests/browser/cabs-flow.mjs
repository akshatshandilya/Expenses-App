// Auto and Cabs ride logging, route management, validation and editing.
import {createRequire} from 'node:module';
import {build} from 'esbuild';
import {mkdirSync,cpSync,readFileSync,existsSync} from 'node:fs';
import http from 'node:http';import path from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const CHROME=process.env.CHROME_PATH||'/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell';
const OUT='tests/.tmp';mkdirSync(OUT+'/www',{recursive:true});
await build({entryPoints:['tests/browser/harness.js'],bundle:true,format:'iife',outfile:OUT+'/www/app.js',logLevel:'error'});
for(const f of ['app.css','index.html','fonts'])cpSync('www/'+f,OUT+'/www/'+f,{recursive:true});
const srv=http.createServer((q,r)=>{const u=q.url.split('?')[0];const f=path.join(OUT,'www',u==='/'?'index.html':u);if(!existsSync(f)){r.writeHead(404);r.end();return;}r.writeHead(200,{'content-type':f.endsWith('.js')?'text/javascript':f.endsWith('.css')?'text/css':'text/html'});r.end(readFileSync(f));}).listen(0);
const browser=await chromium.launch({executablePath:CHROME,args:['--no-sandbox']});
const page=await (await browser.newContext({reducedMotion:'reduce',viewport:{width:390,height:844},locale:'en-IN'})).newPage();page.setDefaultTimeout(5000);
let fails=0;const ok=(n,c)=>{console.log((c?'PASS ':'FAIL ')+n);if(!c)fails++;};
await page.goto(`http://localhost:${srv.address().port}/`);await page.waitForSelector('html.ready');
await page.click('[data-act=start]');
ok('Auto and Cabs appears as a built-in category',await page.locator('[data-act=openCat][data-id=cab]').count()===1);
await page.click('[data-act=openCat][data-id=cab]');
ok('category opens its monthly ride screen',await page.locator('#screen').innerText().then(t=>t.includes('Auto and Cabs')&&t.includes('No rides')));
await page.click('[data-act=routes]');
await page.fill('#rt_rt1','Home to Work');
await page.click('[data-act=addRoute]');
ok('route editor adds a custom route and preserves renamed routes',await page.evaluate(()=>window.__t.S.routes.some(r=>r.name==='Home to Work')&&window.__t.S.routes.some(r=>r.name==='New route')));
await page.click('.sheet button[data-act=closeL]');
await page.click('[data-act=cabAdd]');
await page.click('[data-act=routes]');
await page.fill('#rt_rt2','Work to Home');
await page.click('.sheet button[data-act=closeL]');
ok('route names stay synchronized in an already-open ride form',await page.locator('[data-fk=route]').innerText().then(t=>t.includes('Work to Home')&&t.includes('New route')));
await page.check('input[data-f=mode][value=Cab]');
await page.click('[data-act=seg][data-k=route][data-v=others]');
await page.fill('#f_fare','');
await page.click('[data-act=saveForm]');
ok('fare is required',await page.locator('[data-err=fare]').innerText().then(t=>t.includes('amount above 0')));
await page.fill('#f_fare','230');
await page.click('[data-act=saveForm]');
ok('a one-off route name is required',await page.locator('[data-err=routeOther]').innerText().then(t=>t.includes('Enter the route name')));
await page.fill('#f_routeOther','Airport transfer');
await page.fill('#f_notes','Late-night ride');
await page.click('[data-act=saveForm]');
ok('saved ride contributes its fare and route to the monthly summary',await page.evaluate(()=>{const r=window.__t.S.records.find(x=>x.cat==='cab');return !!r&&r.amountP===23000&&r.party==='Airport transfer'&&r.x.mode==='Cab'&&r.x.routeId==='others';}));
ok('ride list shows the type and one-off route',await page.locator('#screen').innerText().then(t=>t.includes('Cab · Airport transfer')&&t.includes('By route')));
await page.click('[data-act=rec][data-id]');
ok('ride details show the route and type',await page.locator('#layer').innerText().then(t=>t.includes('Airport transfer')&&t.includes('Cab')));
await page.click('[data-act=edit]');
ok('saved ride reopens in the ride editor',await page.locator('#screen').innerText().then(t=>t.includes('Edit ride')&&t.includes('Airport transfer')));
await page.fill('#f_fare','240');
await page.click('[data-act=saveForm]');
ok('editing preserves ride metadata and updates the amount',await page.evaluate(()=>{const r=window.__t.S.records.find(x=>x.cat==='cab');return r.amountP===24000&&r.party==='Airport transfer'&&r.x.mode==='Cab';}));
console.log('browser flow complete');
await browser.close();srv.close();process.exit(fails?1:0);
