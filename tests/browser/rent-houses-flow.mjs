// Rent house selection and automatic saving into the shared Houses settings.
import {createRequire} from 'node:module';
import {build} from 'esbuild';
import {mkdirSync,cpSync,readFileSync,existsSync} from 'node:fs';
import http from 'node:http';import path from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const CHROME=process.env.CHROME_PATH||'/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell';
const OUT='tests/.tmp';mkdirSync(OUT+'/www',{recursive:true});
await build({entryPoints:['tests/browser/harness.js'],bundle:true,format:'iife',outfile:OUT+'/www/app.js',logLevel:'error'});
for(const f of ['app.css','index.html','fonts'])cpSync('www/'+f,OUT+'/www/'+f,{recursive:true});
const srv=http.createServer((q,r)=>{const u=q.url.split('?')[0];const f=path.join(OUT,'www',u==='/'?'index.html':u);if(!existsSync(f)){r.writeHead(404);r.end();return;}r.writeHead(200,{'content-type':f.endsWith('.js')?'text/javascript':f.endsWith('.css')?'text/css':'text/html'});r.end(readFileSync(f));}).listen(0);
const browser=await chromium.launch({executablePath:CHROME,args:['--no-sandbox']});
const page=await(await browser.newContext({reducedMotion:'reduce',viewport:{width:390,height:844},locale:'en-IN'})).newPage();page.setDefaultTimeout(5000);
let fails=0;const ok=(n,c)=>{console.log((c?'PASS ':'FAIL ')+n);if(!c)fails++;};
await page.goto(`http://localhost:${srv.address().port}/`);await page.waitForSelector('html.ready');
await page.click('[data-act=start]');
await page.click('[data-act=openCat][data-id=rent]');
await page.click('[data-act=rentPick][data-v=received]');
await page.click('[data-act=rentAdd]');
ok('rent received quick form labels its status Received, not Paid',await page.locator('[data-act=qaPaid]').innerText().then(t=>t.includes('Received')&&!t.includes('Paid')));
await page.click('[data-act=qaRentAddHouse]');
await page.fill('#qaHouseName','Lakeside Flat');
await page.fill('#qaHouseAddr','Flat 8, Lake Road');
await page.fill('#qaHouseMeter','MTR-808');
await page.fill('#qaAmt','12500');
await page.click('[data-act=qaPaid]');
await page.click('[data-act=qaSave]');
const saved=await page.evaluate(()=>({houses:window.__t.S.houses,record:window.__t.S.records.find(r=>r.cat==='rent')}));
ok('new house details and received rent are saved together',saved.houses.length===1&&saved.houses[0].name==='Lakeside Flat'&&saved.houses[0].addr==='Flat 8, Lake Road'&&saved.houses[0].meter==='MTR-808'&&saved.record.houseId===saved.houses[0].id&&saved.record.dir==='received'&&saved.record.status==='paid');
await page.click('[data-act=rec]');
ok('received rent details show House and Received status',await page.locator('#layer').innerText().then(t=>t.includes('House')&&t.includes('Lakeside Flat')&&t.includes('Status')&&t.includes('Received')));
await page.click('[data-act=edit]');
ok('detailed rent received form labels its checkbox Received',await page.locator('label.sw').innerText().then(t=>t.includes('Received')&&!t.includes('Paid')));
await page.click('[data-act=back]');
await page.click('[data-act=back]');
await page.click('[data-act=rentPick][data-v=paid]');
await page.click('[data-act=rentAdd]');
ok('rent paid quick form offers the saved house as a radio choice',await page.locator('#qaRoot').innerText().then(t=>t.includes('Lakeside Flat')&&t.includes('House')));
await page.click('[data-act=qaMore]');
ok('detailed rent form offers the saved house as a radio choice',await page.locator('[data-fk=houseId]').innerText().then(t=>t.includes('Lakeside Flat')));
ok('rent paid detailed form keeps the Paid label',await page.locator('label.sw').innerText().then(t=>t.includes('Paid')));
await page.check('input[data-f=houseId]');
await page.fill('#f_amount','8700');
await page.locator('label.sw').click({force:true});
await page.click('[data-act=saveForm]');
const paid=await page.evaluate(()=>window.__t.S.records.find(r=>r.cat==='rent'&&r.dir==='paid'));
ok('rent paid record stores the selected shared house ID',!!paid&&paid.houseId===saved.houses[0].id&&paid.party==='Lakeside Flat'&&paid.status==='paid');
await page.click('[data-act=back]');
await page.click('[data-act=back]');
await page.click('[data-act=tab][data-t=settings]');
await page.click('[data-act=houses]');
ok('house created in Rent is available in Settings → Houses',await page.locator('#screen').innerText().then(t=>t.includes('Lakeside Flat')&&t.includes('MTR-808')&&t.includes('rent record')));
console.log('rent house flow complete');
await browser.close();srv.close();process.exit(fails?1:0);
