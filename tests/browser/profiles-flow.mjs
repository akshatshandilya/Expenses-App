// Profiles: add, switch, rename and delete in a real browser engine.
import {createRequire} from 'node:module';
import {build} from 'esbuild';
import {mkdirSync,cpSync,readFileSync,existsSync} from 'node:fs';
import http from 'node:http';import path from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const CHROME=process.env.CHROME_PATH||'/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell';
const OUT='tests/.tmp';mkdirSync(OUT+'/www',{recursive:true});
await build({entryPoints:['tests/browser/harness.js'],bundle:true,format:'iife',outfile:OUT+'/www/app.js',logLevel:'error'});
for(const f of ['app.css','index.html','fonts'])cpSync('www/'+f,OUT+'/www/'+f,{recursive:true});
const srv=http.createServer((q,r)=>{const u=q.url.split('?')[0];const f=path.join(OUT,'www',u==='/'?'index.html':u);if(!existsSync(f)){r.writeHead(404);r.end();return;}r.writeHead(200,{'content-type':f.endsWith('.js')?'text/javascript':f.endsWith('.css')?'text/css':f.endsWith('.woff2')?'font/woff2':'text/html'});r.end(readFileSync(f));}).listen(0);
const browser=await chromium.launch({executablePath:CHROME,args:['--no-sandbox']});
const ctx=await browser.newContext({viewport:{width:390,height:844},locale:'en-IN'});
const page=await ctx.newPage();page.setDefaultTimeout(6000);
const errs=[];page.on('pageerror',e=>errs.push(String(e)));
let fails=0;const ok=(n,c)=>{console.log((c?'PASS ':'FAIL ')+n);if(!c)fails++;};
const sel=a=>`[data-act="${a}"]`;
const click=async(a,extra='')=>{await page.click(sel(a)+extra);await page.waitForTimeout(150);};
await page.goto(`http://localhost:${srv.address().port}/`);
await page.waitForSelector('html.ready',{timeout:8000});
await page.evaluate(()=>{const s=window.__t.S;s.onboarded=true;window.__t.setStack([{n:'home',p:{}}]);window.__t.draw();});
ok('title shows the profile name',await page.evaluate(()=>document.querySelector('.pft').innerText.trim()==='Personal'));
await page.evaluate(()=>{window.__t.setStack([{n:'settings',p:{}}]);window.__t.draw();});
await click('profiles');
ok('profiles list shows Personal',(await page.innerText('#screen')).includes('Personal'));
await click('profNew');ok('new profile screen has the Shared switch, available once the cloud is configured',await page.evaluate(()=>!document.getElementById('pfShared').disabled));await page.fill('#pfName','Home');await click('pfSave');
ok('creating a profile opens it empty on Home with a switcher pill',await page.evaluate(()=>!!document.querySelector('.pft').innerText.includes('Home')&&window.__t.S.records.length===0));
await click('profSwitch');
ok('switcher lists both profiles',(await page.innerText('#layer')).includes('Personal'));
await page.click('#layer [data-act="profOpen"]');await page.waitForTimeout(200);
ok('switching returns to Personal',await page.evaluate(()=>document.querySelector('.pft').innerText.includes('Personal')));
await page.evaluate(()=>{window.__t.setStack([{n:'profiles',p:{}}]);window.__t.draw();});
await click('profNew');await page.fill('#pfName','personal');await click('pfSave');
ok('duplicate name is refused with a message',(await page.innerText('#pnErr')).includes('already'));
await click('back');
await page.click('[data-act="profRename"]');await page.fill('#pnm','Mine');await click('profRenameGo');
ok('rename shows new name',(await page.innerText('#screen')).includes('Mine'));
await page.click('[data-act="profDelete"] >> nth=1');await page.fill('#typed','DELETE');await click('askOk');await page.waitForTimeout(250);
ok('delete leaves one profile',await page.evaluate(()=>window.__t.S.records.length===0&&document.querySelectorAll('[data-act=profDelete]').length===0));
ok('no page errors',errs.length===0);if(errs.length)console.log(errs);
await browser.close();srv.close();process.exit(fails?1:0);
