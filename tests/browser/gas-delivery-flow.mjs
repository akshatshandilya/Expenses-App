import {createRequire} from 'node:module';
import {build} from 'esbuild';
import {mkdirSync,cpSync,readFileSync,existsSync} from 'node:fs';
import http from 'node:http';import path from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const CHROME=process.env.CHROME_PATH||'/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell';
const OUT='tests/.tmp';mkdirSync(OUT+'/www',{recursive:true});
await build({entryPoints:['tests/browser/harness.js'],bundle:true,format:'iife',outfile:OUT+'/www/app.js',logLevel:'error'});
for(const f of ['app.css','index.html','fonts'])cpSync('www/'+f,OUT+'/www/'+f,{recursive:true});
const srv=http.createServer((q,r)=>{const u=q.url.split('?')[0];const f=path.join(OUT,'www',u==='/'?'index.html':u);if(!existsSync(f)){r.writeHead(404);r.end();return;}r.writeHead(200,{'content-type':f.endsWith('.js')?'text/javascript':f.endsWith('.css')?'text/css':f.endsWith('.woff2')?'font/woff2':'text/html'});r.end(readFileSync(f));}).listen(0);
const browser=await chromium.launch({executablePath:CHROME,args:['--no-sandbox']});
const page=await (await browser.newContext({viewport:{width:390,height:844},locale:'en-IN'})).newPage();page.setDefaultTimeout(6000);
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
let fails=0;const ok=(n,c)=>{console.log((c?'PASS ':'FAIL ')+n);if(!c)fails++;};
const text=()=>page.locator('#screen').innerText();
await page.goto(`http://localhost:${srv.address().port}/`);await page.waitForSelector('html.ready');
await page.click('[data-act=start]');
await page.evaluate(()=>{window.__t.S.prices.gas={cur:9000,hist:[{from:'0000-00-00',price:9000}],log:[]};window.__t.draw(true);});
await page.click('[data-act=pick]');
ok('gas picker describes delivery date, quantity and cylinder price',(await text()).includes('Delivery date, quantity and cylinder price'));
await page.click('[data-act=pickGo][data-id=gas]');
ok('gas category hides the saved unit-price chip',await page.locator('.hd .pchip').count()===0);
await page.click('[data-act=catAdd][data-id=gas]');
ok('gas entry is labeled as a delivery',await text().then(t=>t.includes('Add delivery')&&t.includes('Delivery Date')));
ok('gas entry does not prefill the saved unit price',await page.locator('#f_unit').inputValue()==='');
await page.fill('#f_date','2026-11-12');await page.fill('#f_deliveryDate','2026-11-13');
await page.fill('#f_qty','2');await page.fill('#f_unit','85');
await page.click('#saveBtn');
const saved=await page.evaluate(()=>window.__t.S.records.find(r=>r.cat==='gas'));
ok('saved gas entry includes the delivery date and calculated amount',saved&&saved.deliveryDate==='2026-11-13'&&saved.amountP===17000);
await page.click('[data-act=rec][data-id="'+saved.id+'"]');
const details=await page.locator('#layer').innerText();
ok('record details label the delivery date and cylinder price',details.includes('Delivery Date')&&details.includes('Cylinder price'));
await page.click('[data-act=edit][data-id="'+saved.id+'"]');
ok('editing restores the delivery date',await page.locator('#f_deliveryDate').inputValue()==='2026-11-13');
await page.fill('#f_deliveryDate','2026-11-14');await page.click('#saveBtn');
ok('editing saves the updated delivery date',await page.evaluate(id=>window.__t.S.records.find(r=>r.id===id).deliveryDate,saved.id)==='2026-11-14');
ok('no browser script errors',errors.length===0);
await browser.close();srv.close();process.exit(fails?1:0);
